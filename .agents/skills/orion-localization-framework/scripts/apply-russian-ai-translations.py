def phrase_replace(text: str) -> str | None:
    protected, placeholders = BASE.protect(text)
    result = protected
    for phrase, translation in sorted(PHRASE_TRANSLATIONS.items(), key=lambda item: len(item[0]), reverse=True):
        result = re.sub(re.escape(phrase), translation, result, flags=re.IGNORECASE)
    tokens = re.split(r"(\W+)", result)
    changed = False
    for index, token in enumerate(tokens):
        if token in placeholders:
            continue
        if token in WORD_TRANSLATIONS:
            tokens[index] = WORD_TRANSLATIONS[token]
            changed = True
        elif token.lower().capitalize() in WORD_TRANSLATIONS:
            tokens[index] = WORD_TRANSLATIONS[token.lower().capitalize()]
            changed = True
    result = "".join(tokens)
    if result != protected:
        changed = True
    if not changed:
        return None
    return BASE.restore(result, placeholders)


def translate_text(source: str, entry: dict[str, Any], en_cache: dict[str, str], en_by_key: dict[tuple[str, str], str]) -> tuple[str, str]:
    if not source:
        return "", "empty"

    canonical = canonical_source(source, entry, en_cache, en_by_key)
    candidates = [source]
    source_placeholders = set(BASE.PH_RE.findall(source))
    canonical_placeholders = set(BASE.PH_RE.findall(canonical))
    if canonical != source and source_placeholders.issubset(canonical_placeholders):
        candidates.insert(0, canonical)

    for candidate in candidates:
        normalized = normalize_newlines(candidate)
        if normalized in EXACT:
            return restore_newlines(candidate, EXACT[normalized]), "exact"
        long_match = match_long(candidate)
        if long_match is not None:
            return long_match, "long"
        if HAN_RE.search(normalized):
            chinese = translate_chinese(normalized)
            if chinese is not None:
                return restore_newlines(candidate, chinese), "zh"
        pattern = translate_patterns(candidate)
        if pattern is not None:
            return pattern, "pattern"
        phrase = phrase_replace(candidate)
        if phrase is not None:
            return phrase, "phrase"

    if not has_words(source) or BASE.is_nontranslatable(source):
        return source, "nontranslatable"

    # Last resort for rare third-party/demo labels: keep technical names but mark
    # visible English words with a Russian context noun so QA catches them.
    fallback = phrase_replace(source)
    if fallback is not None and fallback != source:
        return fallback, "fallback_phrase"
    return source, "unhandled"


def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("--project-root", default=".")
    parser.add_argument("--targets", nargs="*", default=list(TARGETS))
    parser.add_argument("--culture", default="ru")
    parser.add_argument("--dry-run", action="store_true")
    args = parser.parse_args()

    project_root = Path(args.project_root).resolve()
    cache = load_cache(project_root / "Saved" / "OrionUE" / "Localization" / "translation_cache.json")
    report_rows: list[dict[str, str]] = []
    method_counts: Counter[str] = Counter()
    changed = 0
    unhandled = 0

    for target in args.targets:
        archive_name = TARGETS[target]
        target_root = project_root / "Content" / "Localization" / target
        en_by_key = build_entry_lookup(target_root / "en" / f"{archive_name}.archive")
        archive_path = target_root / args.culture / f"{archive_name}.archive"
        data = read_json_utf16(archive_path)
        for entry in iter_archive_entries(data):
            source = entry.get("Source", {}).get("Text", "")
            translation, method = translate_text(source, entry, cache, en_by_key)
            method_counts[method] += 1
            if method == "unhandled":
                unhandled += 1
            current = entry.setdefault("Translation", {}).get("Text", "")
            if current != translation:
                entry["Translation"]["Text"] = translation
                changed += 1
            report_rows.append({
                "target": target,
                "culture": args.culture,
                "namespace": entry.get("Namespace", ""),
                "key": entry.get("Key", ""),
                "method": method,
                "source": source,
                "translation": translation,
            })
        if not args.dry_run:
            write_json_utf16_crlf(archive_path, data)

    out_dir = project_root / "Saved" / "OrionUE" / "Localization"
    out_dir.mkdir(parents=True, exist_ok=True)
    report_path = out_dir / "russian_ai_translation_report.csv"
    with report_path.open("w", encoding="utf-8-sig", newline="") as handle:
        writer = csv.DictWriter(handle, fieldnames=["target", "culture", "namespace", "key", "method", "source", "translation"])
        writer.writeheader()
        writer.writerows(report_rows)

    summary_path = out_dir / "russian_ai_translation_summary.csv"
    with summary_path.open("w", encoding="utf-8-sig", newline="") as handle:
        writer = csv.writer(handle)
        writer.writerow(["method", "count"])
        for method, count in method_counts.most_common():
            writer.writerow([method, count])

    print(f"changed={changed}")
    print(f"unhandled={unhandled}")
    for method, count in method_counts.most_common():
        print(f"{method}={count}")
    return 1 if unhandled else 0


