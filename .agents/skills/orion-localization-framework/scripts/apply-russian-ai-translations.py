def load_base_helpers() -> Any:
    script_path = Path(__file__).with_name("fill-unreal-archive-translations.py")
    spec = importlib.util.spec_from_file_location("orion_fill_translations", script_path)
    if spec is None or spec.loader is None:
        raise RuntimeError(f"Unable to import {script_path}")
    module = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(module)
    return module


