def read_json_utf16(path: Path) -> Any:
    return json.loads(path.read_text(encoding="utf-16"))


def write_json_utf16_crlf(path: Path, data: Any) -> None:
    text = json.dumps(data, ensure_ascii=False, indent=2)
    text = text.replace("\n", "\r\n")
    path.write_text(text, encoding="utf-16", newline="")


def iter_archive_entries(data: Any) -> list[dict[str, Any]]:
    entries: list[dict[str, Any]] = []

    def walk(obj: Any) -> None:
        if isinstance(obj, dict):
            if "Source" in obj and "Translation" in obj:
                entries.append(obj)
            for value in obj.values():
                walk(value)
        elif isinstance(obj, list):
            for value in obj:
                walk(value)

    walk(data)
    return entries


def normalize_newlines(text: str) -> str:
    return text.replace("\r\n", "\n")


def restore_newlines(reference: str, text: str) -> str:
    if "\r\n" in reference:
        return text.replace("\n", "\r\n")
    return text


def compact(text: str) -> str:
    return " ".join(text.strip().split())


def has_words(text: str) -> bool:
    return bool(WORD_RE.search(text))


def load_cache(path: Path) -> dict[str, str]:
    if not path.exists():
        return {}
    return json.loads(path.read_text(encoding="utf-8"))


def build_entry_lookup(path: Path) -> dict[tuple[str, str], str]:
    if not path.exists():
        return {}
    lookup: dict[tuple[str, str], str] = {}
    data = read_json_utf16(path)
    for entry in iter_archive_entries(data):
        lookup[(entry.get("Namespace", ""), entry.get("Key", ""))] = entry.get("Translation", {}).get("Text", "")
    return lookup


def canonical_source(source: str, entry: dict[str, Any], en_cache: dict[str, str], en_by_key: dict[tuple[str, str], str]) -> str:
    cached = en_cache.get(f"en\n{source}")
    if cached:
        return cached
    key = (entry.get("Namespace", ""), entry.get("Key", ""))
    by_key = en_by_key.get(key, "")
    if by_key and (HAN_RE.search(source) or by_key != source):
        return by_key
    return source


def match_long(text: str) -> str | None:
    normalized = normalize_newlines(text)
    for prefix, translation in LONG_PREFIX_TRANSLATIONS:
        if normalized.startswith(prefix):
            return restore_newlines(text, translation)
    return None


